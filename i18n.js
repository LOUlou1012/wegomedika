function currentLang() { return localStorage.getItem('lang') || 'en'; }

function t(key) {
  const lang = currentLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyLang(lang) {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N[lang] && I18N[lang][key] !== undefined) el.textContent = I18N[lang][key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (I18N[lang] && I18N[lang][key] !== undefined) el.innerHTML = I18N[lang][key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N[lang] && I18N[lang][key] !== undefined) el.placeholder = I18N[lang][key];
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if (I18N[lang] && I18N[lang][key] !== undefined) el.alt = I18N[lang][key];
  });

  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));

  if (typeof renderFilters === 'function') renderFilters();
  if (typeof renderProducts === 'function') renderProducts();
}

function setLang(lang) {
  localStorage.setItem('lang', lang);
  applyLang(lang);
}

document.addEventListener('DOMContentLoaded', () => applyLang(currentLang()));
